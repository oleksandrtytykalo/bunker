#!/usr/bin/env python3
"""Cache-busting for GitHub Pages (which lets browsers reuse files for 10 min).

Rewrites index.html so every stylesheet and JS module is loaded with ?v=<version>.
An import map remaps each module's plain URL to its versioned URL, so the
modules' own relative imports (./engine.js, …) are versioned too.

Run before every deploy:   python3 bump.py && git commit -am "…" && git push
"""
import json, os, time

ROOT = os.path.dirname(os.path.abspath(__file__))
VER = time.strftime('%Y%m%d%H%M%S')

modules = sorted(
    os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/')
    for d, _, files in os.walk(os.path.join(ROOT, 'js')) for f in files if f.endswith('.js')
)
importmap = {'imports': {f'./{m}': f'./{m}?v={VER}' for m in modules}}

html = f"""<!doctype html>
<html lang="uk">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
  <meta name="theme-color" content="#0b0d09" />
  <title>БУНКЕР</title>
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;700&family=Oswald:wght@400;500;600;700&family=Russo+One&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="css/style.css?v={VER}" />
  <link rel="stylesheet" href="css/tv.css?v={VER}" />
  <!-- generated by bump.py: versioned module URLs so browsers never run stale game code -->
  <script type="importmap">
{json.dumps(importmap, indent=2)}
  </script>
</head>
<body>
  <div id="app"></div>
  <div class="fx-scan" aria-hidden="true"></div>
  <div class="fx-noise" aria-hidden="true"></div>
  <div class="fx-vignette" aria-hidden="true"></div>
  <script type="module" src="js/app.js?v={VER}"></script>
</body>
</html>
"""
with open(os.path.join(ROOT, 'index.html'), 'w') as f:
    f.write(html)
print(f'index.html → version {VER} ({len(modules)} modules)')
